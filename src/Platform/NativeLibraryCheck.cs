using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace CloCloWidget;

// The single-file exe unpacks WPF's native DLLs into
// %TEMP%\.net\CloCloWidget\<id>\ on first run and simply reuses that folder
// afterwards — the .NET host doesn't re-check what it finds there (verified:
// a planted file is loaded as-is). Anything running as this user could drop
// a DLL there and have it run inside the signed CloClo process.
//
// So before WPF loads any of them, every DLL in that folder must be one of
// the exact files this build shipped — its name and SHA-256 are compiled
// into the signed exe at build time (NativeLibraryPins.g.cs, generated by
// the csproj). WPF DLLs must also carry an intact Microsoft signature; the
// optional Whisper CPU DLLs must carry the app's own signer. "Any
// Microsoft-signed DLL" alone isn't enough: an older, vulnerable build of
// the same DLL, or some other Microsoft file renamed, would pass that. If a
// file fails, the folder is deleted and CloClo restarts once, which makes
// the host extract clean copies.
//
// It also refuses to start while files sit next to the exe that Windows'
// own loader reads before any code here runs: <exe>.config (side-by-side
// redirects of the system components Windows loads into the process) and
// <exe>.local (DLL redirection), plus <exe>.manifest.
//
// And it checks the exe's own folder the same way: Windows looks there
// first for many system DLLs loaded by name (version.dll, dwmapi.dll,
// winmm.dll… — reproduced), so a look-alike placed beside the exe would be
// loaded into CloClo. Any DLL there must be one of the pinned files (the
// Program Files layout keeps WPF's native DLLs there); anything else makes
// CloClo refuse to start. Re-extracting can't fix that folder, so there's
// no retry for it.
//
// Both folders are checked against an allow-list, not just for DLLs: beside
// the exe only CloClo's own files may be there (the exe, its pinned DLLs, the
// uninstaller, the source checker and its record), and in the unpack folder
// only the pinned DLLs - any other file or any subfolder counts as tampering.
//
// Every DLL that passes is kept open for as long as CloClo runs, shared for
// reading only: Windows can still load it, but nothing can change, rename or
// delete it between this check and the moment WPF loads it - and the hash is
// computed through that same open handle, so what was checked is what loads.
//
// Finally, CloClo doesn't run as administrator (unless User Account Control
// is off, when everything does): a widget that reads other apps' text and
// sends keystrokes has no business holding those rights.
public static partial class NativeLibraryCheck
{
    private const string RetriedVariable = "CLOCLO_NATIVE_REEXTRACTED";

    // Files that may sit beside the exe besides the exe itself and the pinned
    // DLLs. (The .pdb is only there when running from the build output.)
    private static readonly HashSet<string> AllowedAppFiles = new(StringComparer.OrdinalIgnoreCase)
    {
        "uninstall.ps1", "check-source.ps1", "source-manifest.json", "CloCloWidget.pdb",
        "ggml-base.bin", // inert model data, SHA-256 checked before it reaches Whisper
    };

    // The verified DLLs, held open (read-share only) for the process's lifetime.
    private static readonly List<FileStream> HeldOpen = new();

    // Microsoft's code-signing roots, matched by exact name.
    private static readonly HashSet<string> MicrosoftRoots = new(StringComparer.Ordinal)
    {
        "Microsoft Root Certificate Authority",
        "Microsoft Root Certificate Authority 2010",
        "Microsoft Root Certificate Authority 2011",
    };

    // Returns false when the process should exit (it has restarted itself,
    // or refused to run).
    public static bool EnsureTrusted()
    {
        // Only a bundled single-file build extracts anything; in a normal
        // build the assembly has a real path and there's nothing to check.
        // (IL3000 warns that Location is empty inside a single-file app -
        // which is exactly what this tests for.)
#pragma warning disable IL3000
        if (!string.IsNullOrEmpty(typeof(NativeLibraryCheck).Assembly.Location)) return true;
#pragma warning restore IL3000

        if (IsElevated() && IsUacOn())
        {
            Refuse("CloClo doesn't run as administrator. Close it and start it normally - from the Start Menu or " +
                "desktop shortcut, not with \"Run as administrator\" or from an administrator window.");
            return false;
        }

        // A .NET profiler named in the environment is loaded by the runtime
        // before any code here exists, so this can't stop it from loading —
        // but CloClo won't carry on with one attached. Nothing legitimate
        // profiles an installed copy of a desktop widget.
        var profiler = ProfilerVariables().ToList();
        if (profiler.Count > 0)
        {
            Refuse("CloClo won't run with a .NET profiler attached. These environment variables load one:\n\n" +
                string.Join("\n", profiler) +
                "\n\nCloClo never sets them. Remove them (System Properties -> Environment Variables), " +
                "sign out and back in, and consider a malware scan.");
            return false;
        }

        var sideFiles = LoaderSideFiles().ToList();
        if (sideFiles.Count > 0)
        {
            Refuse("CloClo won't start while these files are next to it:\n\n" +
                string.Join("\n", sideFiles.Select(Path.GetFileName)) +
                "\n\nWindows reads them when starting CloClo and they can change what gets loaded into it. " +
                "CloClo never creates them - delete them, then start CloClo again.");
            return false;
        }

        if (PinnedLibraries.Count == 0)
        {
            Refuse("This build of CloClo carries no list of its native files, so it can't verify them. Reinstall CloClo.");
            return false;
        }

        var appDir = Path.TrimEndingDirectorySeparator(AppContext.BaseDirectory);
        var exeName = Path.GetFileName(Environment.ProcessPath!);
        var strangers = new List<string>();
        foreach (var entry in Directory.EnumerateFileSystemEntries(appDir))
        {
            var name = Path.GetFileName(entry);
            if (Directory.Exists(entry)) strangers.Add(name + "\\");
            else if (name.Equals(exeName, StringComparison.OrdinalIgnoreCase) || AllowedAppFiles.Contains(name)) continue;
            else if (!name.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) || !HoldIfVerified(entry)) strangers.Add(name);
        }
        if (strangers.Count > 0)
        {
            ReleaseAll();
            Refuse("CloClo won't start while these are next to it:\n\n" +
                string.Join("\n", strangers) +
                "\n\nThey aren't part of CloClo, and Windows could load them into it. " +
                "Delete them (and consider a malware scan), then start CloClo again.");
            return false;
        }

        var extractDirs = ExtractionDirectories().ToList();
        var bad = new List<string>();
        foreach (var dir in extractDirs)
        {
            foreach (var entry in Directory.EnumerateFileSystemEntries(dir))
            {
                var name = Path.GetFileName(entry);
                if (Directory.Exists(entry)) bad.Add(name + "\\");
                else if (!name.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) || !HoldIfVerified(entry)) bad.Add(name);
            }
        }
        if (bad.Count == 0) return true;
        ReleaseAll();

        if (Environment.GetEnvironmentVariable(RetriedVariable) == "1")
        {
            Refuse("CloClo found native files it can't verify and won't run with them:\n\n" +
                string.Join("\n", bad) +
                "\n\nReinstall CloClo, and consider a malware scan.");
            return false;
        }

        foreach (var dir in extractDirs)
        {
            try { Directory.Delete(dir, recursive: true); } catch { /* best effort; the retry check catches it */ }
        }
        var restart = new ProcessStartInfo(Environment.ProcessPath!) { UseShellExecute = false };
        restart.Environment[RetriedVariable] = "1";
        using var restartedProcess = Process.Start(restart);
        return false;
    }

    // Opens the DLL shared for reading only and keeps it open: Windows can still
    // load it, but nothing can change, rename or delete it from now on. The hash
    // is read through this same handle, so the checked bytes are the loaded ones.
    private static bool HoldIfVerified(string path)
    {
        FileStream? stream = null;
        try
        {
            stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
            var hash = Convert.ToHexString(SHA256.HashData(stream));
            var identity = $"{Path.GetFileName(path)}|{hash}";
            if ((PinnedLibraries.Contains(identity) && IsMicrosoftSigned(path)) ||
                (PinnedWhisperLibraries.Contains(identity) && HasSameSignerAsExe(path)))
            {
                HeldOpen.Add(stream);
                return true;
            }
        }
        catch
        {
            // unreadable or locked by someone else: not verified
        }
        stream?.Dispose();
        return false;
    }

    private static void ReleaseAll()
    {
        foreach (var s in HeldOpen) s.Dispose();
        HeldOpen.Clear();
    }

    private static bool IsElevated()
    {
        using var identity = System.Security.Principal.WindowsIdentity.GetCurrent();
        return new System.Security.Principal.WindowsPrincipal(identity).IsInRole(System.Security.Principal.WindowsBuiltInRole.Administrator);
    }

    private static bool IsUacOn()
    {
        using var key = Microsoft.Win32.Registry.LocalMachine.OpenSubKey(@"SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System");
        return key?.GetValue("EnableLUA") is not int value || value != 0;
    }

    // Windows' own message box: this runs before WPF may load (its native
    // DLLs aren't verified yet), so a WPF MessageBox can't be used here.
    private static void Refuse(string message) =>
        MessageBoxW(IntPtr.Zero, message, "CloClo", 0x30 /* MB_ICONWARNING */ | 0x10000 /* MB_SETFOREGROUND */);

    [System.Runtime.InteropServices.DllImport("user32.dll", CharSet = System.Runtime.InteropServices.CharSet.Unicode)]
    private static extern int MessageBoxW(IntPtr hwnd, string text, string caption, uint type);

    // CORECLR_ENABLE_PROFILING / CORECLR_PROFILER(_PATH)(_32/_64) attach a
    // startup profiler, CORECLR_ENABLE_NOTIFICATION_PROFILERS more of them;
    // the DOTNET_/COMPlus_ spellings cover the runtime's other config names.
    private static IEnumerable<string> ProfilerVariables()
    {
        foreach (System.Collections.DictionaryEntry entry in Environment.GetEnvironmentVariables())
        {
            var name = (string)entry.Key;
            if (string.IsNullOrWhiteSpace(entry.Value as string)) continue;
            var isProfiler = name.StartsWith("CORECLR_", StringComparison.OrdinalIgnoreCase)
                || ((name.StartsWith("DOTNET_", StringComparison.OrdinalIgnoreCase) || name.StartsWith("COMPlus_", StringComparison.OrdinalIgnoreCase))
                    && name.Contains("Profil", StringComparison.OrdinalIgnoreCase));
            if (isProfiler) yield return name;
        }
    }

    private static IEnumerable<string> LoaderSideFiles()
    {
        var exe = Environment.ProcessPath!;
        foreach (var suffix in new[] { ".config", ".local", ".manifest" })
        {
            var path = exe + suffix;
            if (File.Exists(path) || Directory.Exists(path)) yield return path;
        }
    }

    // The runtime's native probing directories, minus the exe's own folder —
    // for a single-file build that leaves exactly the extraction folder.
    internal static IEnumerable<string> ExtractionDirectories()
    {
        var appDir = Path.TrimEndingDirectorySeparator(AppContext.BaseDirectory);
        var dirs = (AppContext.GetData("NATIVE_DLL_SEARCH_DIRECTORIES") as string ?? "")
            .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
            .Select(Path.TrimEndingDirectorySeparator)
            .Distinct(StringComparer.OrdinalIgnoreCase);
        return dirs.Where(d => !d.Equals(appDir, StringComparison.OrdinalIgnoreCase) && Directory.Exists(d));
    }

    private static bool IsMicrosoftSigned(string path)
    {
        if (WinVerifyTrustFile(path) != 0) return false; // missing, tampered or untrusted
        try
        {
#pragma warning disable SYSLIB0057 // only the signer certificate is read; the file's integrity came from WinVerifyTrust
            using var signer = new X509Certificate2(X509Certificate.CreateFromSignedFile(path));
#pragma warning restore SYSLIB0057
            // Microsoft signs these under several names ("Microsoft Windows",
            // ".NET"…) but always as the organization Microsoft Corporation,
            // and always under one of Microsoft's own roots — which no other
            // certificate authority can issue into.
            if (!IsMicrosoftCorporation(signer)) return false;
            using var chain = new X509Chain();
            chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;
            // This chain only identifies the root. Whether the signature is
            // valid was already settled by WinVerifyTrust, which honours the
            // signing timestamp — several of these DLLs were signed with
            // certificates that have since expired, which is fine.
            chain.ChainPolicy.VerificationFlags = X509VerificationFlags.IgnoreNotTimeValid | X509VerificationFlags.IgnoreCtlNotTimeValid;
            if (!chain.Build(signer)) return false;
            var root = chain.ChainElements[^1].Certificate;
            return IsMicrosoftCorporation(root)
                && MicrosoftRoots.Contains(root.GetNameInfo(X509NameType.SimpleName, false) ?? "");
        }
        catch
        {
            return false;
        }
    }

    // Voice commands may launch only fixed Microsoft executables in protected
    // Windows or Program Files locations. Reuse the existing signature check.
    internal static bool IsTrustedMicrosoftExecutable(string path) => IsMicrosoftSigned(path);

    // Hash matching is mandatory, including for self-signed CloClo builds.
    // A signed installation additionally requires each Whisper DLL to carry
    // the exact signer certificate of the executable. The hash was compiled
    // into that executable after the DLL copy was signed.
    private static bool HasSameSignerAsExe(string path)
    {
        X509Certificate2? exeSigner;
        try
        {
#pragma warning disable SYSLIB0057 // signers only; the pinned hash checks file integrity
            exeSigner = new X509Certificate2(X509Certificate.CreateFromSignedFile(Environment.ProcessPath!));
#pragma warning restore SYSLIB0057
        }
        catch
        {
            // Unsigned local build: only accept an unsigned pinned DLL.
            try
            {
#pragma warning disable SYSLIB0057
                using var dllSigner = new X509Certificate2(X509Certificate.CreateFromSignedFile(path));
#pragma warning restore SYSLIB0057
                return false;
            }
            catch { return true; }
        }
        using (exeSigner)
        {
            try
            {
#pragma warning disable SYSLIB0057
                using var dllSigner = new X509Certificate2(X509Certificate.CreateFromSignedFile(path));
#pragma warning restore SYSLIB0057
                return exeSigner.Thumbprint == dllSigner.Thumbprint;
            }
            catch { return false; }
        }
    }

    private static bool IsMicrosoftCorporation(X509Certificate2 cert) =>
        cert.SubjectName.EnumerateRelativeDistinguishedNames()
            .Any(rdn => rdn.GetSingleElementType().Value == "2.5.4.10" // O=
                && rdn.GetSingleElementValue() == "Microsoft Corporation");

    // ---- WinVerifyTrust: checks the file's hash against its signature and
    // that the certificate chains to a trusted root. Offline only (no
    // revocation fetch), so startup never waits on the network.

    private static readonly Guid GenericVerifyV2 = new("00AAC56B-CD44-11d0-8CC2-00C04FC295EE");

    private static int WinVerifyTrustFile(string path)
    {
        var fileInfo = new WINTRUST_FILE_INFO
        {
            cbStruct = (uint)Marshal.SizeOf<WINTRUST_FILE_INFO>(),
            pcwszFilePath = path,
        };
        var fileInfoPtr = Marshal.AllocHGlobal(Marshal.SizeOf<WINTRUST_FILE_INFO>());
        try
        {
            Marshal.StructureToPtr(fileInfo, fileInfoPtr, false);
            var data = new WINTRUST_DATA
            {
                cbStruct = (uint)Marshal.SizeOf<WINTRUST_DATA>(),
                dwUIChoice = 2,            // WTD_UI_NONE
                fdwRevocationChecks = 0,   // WTD_REVOKE_NONE
                dwUnionChoice = 1,         // WTD_CHOICE_FILE
                pFile = fileInfoPtr,
                dwStateAction = 0,         // WTD_STATEACTION_IGNORE
                dwProvFlags = 0x1000,      // WTD_CACHE_ONLY_URL_RETRIEVAL
            };
            var action = GenericVerifyV2;
            return WinVerifyTrust(new IntPtr(-1), ref action, ref data);
        }
        finally
        {
            Marshal.DestroyStructure<WINTRUST_FILE_INFO>(fileInfoPtr);
            Marshal.FreeHGlobal(fileInfoPtr);
        }
    }

    [DllImport("wintrust.dll", CharSet = CharSet.Unicode)]
    private static extern int WinVerifyTrust(IntPtr hwnd, ref Guid pgActionID, ref WINTRUST_DATA pWVTData);

    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    private struct WINTRUST_FILE_INFO
    {
        public uint cbStruct;
        [MarshalAs(UnmanagedType.LPWStr)] public string pcwszFilePath;
        public IntPtr hFile;
        public IntPtr pgKnownSubject;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct WINTRUST_DATA
    {
        public uint cbStruct;
        public IntPtr pPolicyCallbackData;
        public IntPtr pSIPClientData;
        public uint dwUIChoice;
        public uint fdwRevocationChecks;
        public uint dwUnionChoice;
        public IntPtr pFile;
        public uint dwStateAction;
        public IntPtr hWVTStateData;
        public IntPtr pwszURLReference;
        public uint dwProvFlags;
        public uint dwUIContext;
        public IntPtr pSignatureSettings;
    }
}
