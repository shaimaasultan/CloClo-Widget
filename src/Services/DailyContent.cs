    public sealed record Quote(string Text, string Author, string? Arabic = null);

    // English, its Arabic translation and transliteration, and a short
    // example sentence in both languages.
    public sealed record Word(string English, string Arabic, string Transliteration, string Example, string ExampleArabic);

    public sealed record Joke(string Setup, string Punchline);

    public static Quote TodaysQuote(DateTime day) => Pick(Quotes, day);
    public static Word TodaysWord(DateTime day) => Pick(Words, day);
    public static Joke TodaysJoke(DateTime day) => Pick(Jokes, day);
    public static string TodaysFact(DateTime day) => Pick(Facts, day);

    private static T Pick<T>(T[] items, DateTime day) => items[DateOnly.FromDateTime(day).DayNumber % items.Length];

