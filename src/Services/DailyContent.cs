// Today's quote, Arabic word, joke and "did you know" fact. Everything is
// written here and compiled into the signed exe - nothing is fetched, so
// there's no new network connection and no outside text shown in the
// widget. Each list rotates by date: one item per day, the same all day,
// and every item comes round before any repeats.
public static class DailyContent
